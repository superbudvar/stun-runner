static void test_listing_constants(void)
{
    /* move.l #$300,D1 at 0x0298AA / 0x0298E4 and the addq.l/cmp.l/blt triple. */
    check_eq(STUNRUN_ROAD_WINDOW_BYTES, 0x300u);
    /* The FIFO drain at 0x02248E reads 384 halfwords from the base window. */
    check_eq(STUNRUN_ROAD_WINDOW_WORDS, 384u);
    /* movea.l #$FF9884,A0 minus movea.l #$FF9584,A1 at 0x0298B0/0x0298B6. */
    check_eq(STUNRUN_ROAD_WINDOW_TWIN_STRIDE, 0x300u);
    check_eq(STUNRUN_ROAD_WINDOW_TWIN_ADDR - STUNRUN_ROAD_WINDOW_BASE_ADDR,
             STUNRUN_ROAD_WINDOW_TWIN_STRIDE);
    /* move.l #$FF9584,$FFDB3C at 0x0298C8 and 0x029902. */
    check_eq(STUNRUN_ROAD_WINDOW_ACTIVE_ADDR, 0xFFDB3Cu);
    check_eq(STUNRUN_ROAD_WINDOW_LATCH_ADDR, 0xFF954Eu);
    check_eq(STUNRUN_ROAD_WINDOW_BASE_ADDR, 0xFF9584u);
    check_eq(STUNRUN_ROAD_WINDOW_TWIN_ADDR, 0xFF9884u);
    /* move.l #$78,$FF954E at 0x02449E -- the documented startup value. */
    check_eq(0x78u, 120u);
}

/* ------------------------------------------------------------------ */
/* 0x029924 / 0x029AE2: subq.w #1,$FF954E ; beq <expiry>                 */
/* ------------------------------------------------------------------ */

static void test_gate_branch_on_result(void)
{
    stunrun_road_window w;
    uint8_t scratch[STUNRUN_ROAD_WINDOW_BYTES];

    /* latch 1 -> result 0 -> beq taken -> NO pass. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 1u);
    check_eq(stunrun_road_window_gate(&w), STUNRUN_ROAD_PASS_NONE);
    check_eq(stunrun_road_window_latch(&w), 0u);

    /* Through the combined step: the same latch value suppresses the pass. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 1u);
    check_eq(stunrun_road_window_step_subtract(&w), 0);
    check_eq(stunrun_road_window_latch(&w), 0u);

    /* A second step with the latch now at 0 does run the pass, because
     * `subq.w #1` wraps 0 to 0xFFFF and `beq` therefore does not fire. That is
     * the ROM behaviour, not a modelling shortcut: the latch reaching zero does
     * not stop the transform, it arms it for the next call. */
    check_eq(stunrun_road_window_step_subtract(&w), 1);
    check_eq(stunrun_road_window_latch(&w), 0xFFFFu);

    /* latch 0 -> 0xFFFF -> beq clear -> pass. subq.w wraps on a word. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 0u);
    check_eq(stunrun_road_window_gate(&w), STUNRUN_ROAD_PASS_SUBTRACT);
    check_eq(stunrun_road_window_latch(&w), 0xFFFFu);

    /* Observed burst cadence: the latch ran 7,7,6,6,6,5,5,5,4,... over the
     * late_drive frames 524..534, decrementing once per three frames. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 7u);
    check_eq(stunrun_road_window_gate(&w), STUNRUN_ROAD_PASS_SUBTRACT);
    check_eq(stunrun_road_window_latch(&w), 6u);
    check_eq(stunrun_road_window_gate(&w), STUNRUN_ROAD_PASS_SUBTRACT);
    check_eq(stunrun_road_window_latch(&w), 5u);

    /* The add-path gate uses the same instruction, so it selects a pass for the
     * same latch values. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 1u);
    check_eq(stunrun_road_window_step_add(&w), 0);
    check_eq(stunrun_road_window_latch(&w), 0u);
    stunrun_road_window_latch_store(&w, 4u);
    check_eq(stunrun_road_window_step_add(&w), 1);
    check_eq(stunrun_road_window_latch(&w), 3u);

    /* A latch of 0xFFFF must not be mistaken for zero. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 0xFFFFu);
    check_eq(stunrun_road_window_gate(&w), STUNRUN_ROAD_PASS_SUBTRACT);
    check_eq(stunrun_road_window_latch(&w), 0xFFFEu);

    /* 0x02978E / 0x02988A overwrite the same word with the divisor byte. This
     * is why a settled window can be observed with $FF954E == 1 (the divisor
     * the loader was called with) rather than with a countdown. */
    stunrun_road_window_init(&w, scratch, scratch);
    stunrun_road_window_latch_store(&w, 0x1234u);
    stunrun_road_window_latch_load_divisor(&w, 8u);
    check_eq(stunrun_road_window_latch(&w), 8u);
    check_eq(stunrun_road_window_divisor(&w), 8u);
}

/* ------------------------------------------------------------------ */
/* 0x0298C0: sub.b D0,(A1)+ over 0x300 bytes, base only                 */
/* ------------------------------------------------------------------ */

static void test_subtract_pass_against_oracle(void)
{
    stunrun_road_window w;
    uint8_t base[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t twin[STUNRUN_ROAD_WINDOW_BYTES];
    size_t i;
    size_t first;

    memcpy(base, sub_base_before, sizeof(base));
    memcpy(twin, sub_twin, sizeof(twin));

    stunrun_road_window_init(&w, base, twin);
    stunrun_road_window_latch_store(&w, 6u);

    /* Frame 525 -> 526 of the recorded burst: the gate fires and the subtract
     * pass runs. */
    check_eq(stunrun_road_window_step_subtract(&w), 1);
    check_eq(stunrun_road_window_latch(&w), 5u);

    check_window(base, sub_base_after, "subtract pass result");

    /* The twin must be untouched: compare against the literal oracle twin,
     * not against a copy taken before the call. */
    check_window(twin, sub_twin, "twin after subtract pass");

    /* Observed per-pass byte change count for this frame pair. */
    {
        size_t changed = 0u;
        for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++) {
            if (base[i] != sub_base_before[i]) {
                changed++;
            }
        }
        check_eq(changed, 704u);
    }

    /* $FFDB3C was written by the pass. */
    check_eq(stunrun_road_window_active(&w), STUNRUN_ROAD_WINDOW_BASE_ADDR);

    /* Divergence is what a snapshot would have shown at this frame. */
    check_eq(stunrun_road_window_divergence(&w, &first), 731u);
    check_eq(first, 0u);

    /* The pass must not have been a no-op that happens to leave the twin
     * alone: base and twin must now disagree at byte 0 (0xC1 vs 0x1F). */
    check(base[0] != twin[0]);
}


/* Observable-output self-check for the road window transform.
 *
 * Expectations come from two independent places, never from this
 * implementation:
 *
 *   - literal constants read out of the pinned 68010 listing
 *     (sha256 171e56ccf1a9940635a2e8e9929ab7edaa5841ac3238ef78acf0d6630f8e45e7)
 *   - whole-window buffer pairs captured from the MAME oracle
 *
 * The buffer assertions compare 768 bytes against the emulator's bytes. They
 * are NOT of the form `assert(out[i] == in[i] - twin[i])`, which would only
 * restate the implementation and would pass for any loop that is internally
 * consistent -- including a wrong one.
 *
 * A check counter guards the suite against the failure mode where a broken
 * test binary matches zero tests and reads exactly like a pass. The process
 * fails if the counter is zero.
 */
#include <stdio.h>
#include <string.h>

#include "road_window.h"

static int failures;
static unsigned long checks;

#define check(cond) do { \
    checks++; \
    if (!(cond)) { printf("FAIL %s:%d %s\n", __FILE__, __LINE__, #cond); \
                   failures++; } \
} while (0)

#define check_eq(actual, expected) do { \
    checks++; \
    if ((actual) != (expected)) { \
        printf("FAIL %s:%d %s == 0x%lX, expected 0x%lX\n", __FILE__, __LINE__, \
               #actual, (unsigned long)(actual), (unsigned long)(expected)); \
        failures++; \
    } \
} while (0)

static void check_window(const uint8_t *actual, const uint8_t *expected,
                         const char *label)
{
    size_t i;
    int ok = 1;

    for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++) {
        if (actual[i] != expected[i]) {
            printf("FAIL %s byte %u: got 0x%02X expected 0x%02X\n", label,
                   (unsigned)i, actual[i], expected[i]);
            failures++;
            ok = 0;
            break;
        }
    }
    checks++;
    (void)ok;
}



/* The two passes are different operations. Running the subtract pass on the
 * add fixture must NOT reproduce the add fixture's oracle output -- this is the
 * control that would catch an implementation that had the two bodies swapped
 * while still passing a symmetric "add then subtract returns the input" test. */
static void test_passes_are_not_interchangeable(void)
{
    stunrun_road_window w;
    uint8_t base[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t twin[STUNRUN_ROAD_WINDOW_BYTES];
    int i;
    int identical = 1;

    memcpy(base, add_base_before, sizeof(base));
    memcpy(twin, add_twin, sizeof(twin));
    stunrun_road_window_init(&w, base, twin);
    stunrun_road_window_subtract(&w);
    for (i = 0; i < (int)STUNRUN_ROAD_WINDOW_BYTES; i++) {
        if (base[i] != add_base_after[i]) {
            identical = 0;
            break;
        }
    }
    check(identical == 0);
}

/* A subtract immediately followed by an add restores the pre-pass window byte
 * for byte, because both operations are mod-256 and exact inverses. This is
 * the one identity the slice is allowed to assert as a formula, and it is
 * asserted against the literal oracle input, not against a re-derived value. */
static void test_subtract_add_round_trip(void)
{
    stunrun_road_window w;
    uint8_t base[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t twin[STUNRUN_ROAD_WINDOW_BYTES];

    memcpy(base, sub_base_before, sizeof(base));
    memcpy(twin, sub_twin, sizeof(twin));
    stunrun_road_window_init(&w, base, twin);
    check_eq(stunrun_road_window_subtract(&w), 1);
    check_eq(stunrun_road_window_add(&w), 1);
    check_window(base, sub_base_before, "round trip restored the oracle input");
    check_window(twin, sub_twin, "round trip left the twin alone");
}

/* ------------------------------------------------------------------ */
/* Loader + divisor latch + divergence                                   */
/* ------------------------------------------------------------------ */

/* Observed: the settled race fixtures carry $FF954E == 1 (loader divisor 1),
 * which is why base and twin are byte-identical there. Reconstruct that: a
 * divisor-1 load must produce a window whose base equals its twin. */
static void test_divisor_one_load_reproduces_identical_copies(void)
{
    stunrun_road_window w;
    uint8_t source[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t base[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t twin[STUNRUN_ROAD_WINDOW_BYTES];
    size_t i;

    /* Use the oracle's twin as the "source": it is not ROM, and it is a real
     * buffer the emulator held. */
    memcpy(source, sub_twin, sizeof(source));

    stunrun_road_window_init(&w, base, twin);
    memset(base, 0xAAu, sizeof(base));
    memset(twin, 0x55u, sizeof(twin));

    check_eq(stunrun_road_window_load(&w, source, 1u, STUNRUN_ROAD_WINDOW_BYTES), 1);
    check_eq(stunrun_road_window_latch(&w), 1u);
    check_window(base, source, "divisor-1 base copy");
    check_window(twin, source, "divisor-1 twin copy");
    check_eq(stunrun_road_window_divergence(&w, NULL), 0u);

    /* A divisor-8 load must NOT produce identical copies. The oracle shows the
     * twin of the same table at divisor 8 (twin == base/8 byte-wise). */
    memset(base, 0xAAu, sizeof(base));
    memset(twin, 0x55u, sizeof(twin));
    check_eq(stunrun_road_window_load(&w, source, 8u, STUNRUN_ROAD_WINDOW_BYTES), 1);
    check_eq(stunrun_road_window_latch(&w), 8u);
    for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++) {
        if (twin[i] != (uint8_t)(source[i] / 8u)) {
            break;
        }
    }
    check_eq(i, STUNRUN_ROAD_WINDOW_BYTES);
    check(stunrun_road_window_divergence(&w, NULL) != 0u);

    /* A zero divisor would raise a 68010 divide-by-zero exception in
     * `divu.w D1,D0`. The slice rejects it rather than modelling the
     * exception, and must leave the window untouched when it does.
     *
     * Note on coverage: the rejection is enforced by BOTH this layer and
     * stunrun_road_buffer_copy_scaled, so deleting this layer's divisor check
     * is not observable through this slice's public surface -- the callee
     * refuses the same call. That is defence in depth, not a missing test, but
     * it does mean the divisor-0 case here cannot distinguish the two layers. */
    memset(base, 0xAAu, sizeof(base));
    memset(twin, 0x55u, sizeof(twin));
    check_eq(stunrun_road_window_load(&w, source, 0u, STUNRUN_ROAD_WINDOW_BYTES), 0);
    check_eq(base[0], 0xAAu);
    check_eq(twin[0], 0x55u);
    check_eq(stunrun_road_window_latch(&w), 8u);
}

/* ------------------------------------------------------------------ */
/* Geometry view (the GL seam)                                           */
/* ------------------------------------------------------------------ */

static void test_geometry_view(void)
{
    stunrun_road_window w;
    stunrun_road_geometry view;
    uint8_t base[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t twin[STUNRUN_ROAD_WINDOW_BYTES];
    uint16_t words[STUNRUN_ROAD_WINDOW_WORDS];
    uint16_t slice[4];
    uint8_t byte;

    memcpy(base, sub_base_before, sizeof(base));
    memcpy(twin, sub_twin, sizeof(twin));
    stunrun_road_window_init(&w, base, twin);

    /* Whole-window base view: a GL backend gets a pointer, a word count and a
     * stride, and never touches the raw bytes. */
    check_eq(stunrun_road_window_geometry_base(&w, words,
                                               STUNRUN_ROAD_WINDOW_WORDS, &view),
             1);
    check(view.words == words);
    check_eq(view.count, 384u);
    check_eq(view.stride_words, 384u);
    check_eq(view.offset_words, 0u);

    /* Big-endian decode. These are the oracle's bytes 0..7 read as words:
     * E0 E0 E0 12 1F 2C 65 00. A host-endian cast would give 0xE0E0 too for
     * word 0 but 0x12E0 for word 1 instead of 0xE012. */
    check_eq(words[0], 0xE0E0u);
    check_eq(words[1], 0xE012u);
    check_eq(words[2], 0x1F2Cu);
    check_eq(words[3], 0x6500u);

    /* Bounded slice: offset 191 with 4 words, from the same buffer. */
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_BASE, 191u, 4u,
                                          slice, 4u, &view),
             1);
    check_eq(view.offset_words, 191u);
    check_eq(view.count, 4u);
    check_eq(slice[0], 0x0E17u);
    check_eq(slice[1], words[192]);
    check_eq(slice[2], words[193]);
    check_eq(slice[3], words[194]);

    /* A count that would run off the end is refused, not truncated. */
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_BASE, 383u, 2u,
                                          slice, 4u, &view),
             0);
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_BASE, 385u, 0u,
                                          slice, 4u, &view),
             0);
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_BASE, 0u, 4u,
                                          slice, 3u, &view),
             0);
    check_eq(view.words == NULL, 1);

    /* The mirror is reachable through the same descriptor and is not modified
     * by a pass. */
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_TWIN, 0u, 1u,
                                          slice, 4u, &view),
             1);
    check_eq(slice[0], 0x1F1Fu);
    check_eq(stunrun_road_window_subtract(&w), 1);
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_TWIN, 0u, 1u,
                                          slice, 4u, &view),
             1);
    check_eq(slice[0], 0x1F1Fu);
    check_eq(stunrun_road_window_geometry(&w, STUNRUN_ROAD_BUFFER_BASE, 0u, 1u,
                                          slice, 4u, &view),
             1);
    check_eq(slice[0], 0xC1C1u);

    /* Byte accessor agrees with the word view. */
    check_eq(stunrun_road_window_byte(&w, STUNRUN_ROAD_BUFFER_BASE, 0u, &byte), 1);
    check_eq(byte, 0xC1u);
    check_eq(stunrun_road_window_byte(&w, STUNRUN_ROAD_BUFFER_TWIN, 0u, &byte), 1);
    check_eq(byte, 0x1Fu);
    check_eq(stunrun_road_window_byte(&w, STUNRUN_ROAD_BUFFER_BASE,
                                      STUNRUN_ROAD_WINDOW_BYTES, &byte),
             0);

    /* An unbound window is inert rather than a crash. */
    stunrun_road_window_init(&w, NULL, NULL);
    check_eq(stunrun_road_window_subtract(&w), 0);
    check_eq(stunrun_road_window_add(&w), 0);
    check_eq(stunrun_road_window_geometry_base(&w, words, 1u, &view), 0);
    check_eq(stunrun_road_window_byte(&w, STUNRUN_ROAD_BUFFER_BASE, 0u, &byte), 0);
    check_eq(stunrun_road_window_divergence(&w, NULL), 0u);
}

static void test_subtract_pass_covers_the_final_byte(void)
{
    /* A COVERAGE-GAP FIXTURE, not oracle data.
     *
     * The oracle subtract fixture has sub_twin[767] == 0x00, so
     * base[767] - twin[767] == base[767] and a walk that stopped at 767 bytes
     * produced byte-for-byte identical output.  The off-by-one was therefore
     * invisible through every oracle-backed assertion: the checked field was
     * the one byte the operation cannot change.
     *
     * The add fixture does not share the defect (add_twin[767] == 0x17), which
     * is why mutating the ADD loop is caught and mutating the SUBTRACT loop was
     * not.  A test that mirrors an implementation's blind spot is not a test.
     * This vector puts a nonzero twin byte in the last position so the final
     * iteration is observable.  Values are synthetic and labelled as such; they
     * assert the mechanism, not the game.
     */
    stunrun_road_window w;
    uint8_t base[STUNRUN_ROAD_WINDOW_BYTES];
    uint8_t twin[STUNRUN_ROAD_WINDOW_BYTES];
    size_t i;

    for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++) {
        base[i] = (uint8_t)(0x40u + (i & 0x1Fu));
        twin[i] = (uint8_t)(0x11u + (i & 0x07u));
    }
    /* The last three bytes must be non-idempotent under subtraction, so a
     * truncated walk is visible in each of them. */
    check_eq(twin[STUNRUN_ROAD_WINDOW_BYTES - 1u], 0x11u + 7u);
    check_eq(twin[STUNRUN_ROAD_WINDOW_BYTES - 2u], 0x11u + 6u);
    check_eq((int)(base[STUNRUN_ROAD_WINDOW_BYTES - 1u] !=
                   twin[STUNRUN_ROAD_WINDOW_BYTES - 1u]), 1);

    stunrun_road_window_init(&w, base, twin);
    stunrun_road_window_latch_store(&w, 6u);
    check_eq(stunrun_road_window_step_subtract(&w), 1);

    for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++)
        check_eq((unsigned)base[i],
                 (unsigned)(uint8_t)((0x40u + (i & 0x1Fu)) -
                                     (0x11u + (i & 0x07u))));

    /* The same vector through the add path, for symmetry: the two passes must
     * remain distinguishable when the final byte is significant. */
    for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++) {
        base[i] = (uint8_t)(0x40u + (i & 0x1Fu));
        twin[i] = (uint8_t)(0x11u + (i & 0x07u));
    }
    stunrun_road_window_init(&w, base, twin);
    stunrun_road_window_latch_store(&w, 6u);
    check_eq(stunrun_road_window_step_add(&w), 1);
    for (i = 0u; i < STUNRUN_ROAD_WINDOW_BYTES; i++)
        check_eq((unsigned)base[i],
                 (unsigned)(uint8_t)((0x40u + (i & 0x1Fu)) +
                                     (0x11u + (i & 0x07u))));
}

